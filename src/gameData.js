function parseBlueprint(rows, legend, levelId) {
  return rows.flatMap((row, rowIndex) =>
    [...row].flatMap((symbol, colIndex) => {
      const material = legend[symbol];
      if (!material) return [];
      return [
        {
          id: `${levelId}-${rowIndex}-${colIndex}`,
          material,
          row: rowIndex,
          col: colIndex,
        },
      ];
    }),
  );
}

